    S[b2:b2 + 1] = [M, W]                       # исходный сдвоенный блок 2 заменяем двумя
    vc = d('Витрина цен')
    S.insert(vc, R)                             # «Реальная цена» — перед ценой эфира
    cta = d('CTA 1') + 1
