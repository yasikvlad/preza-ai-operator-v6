added = 0
for num, name, anchor, slides in BLOCKS:
    key = anchor.split(':', 1)[1]
    pos = d(key)
    if pos is None:
        pos = len(S) - 1
    new = []
    for sl in slides:
        s = {'a': 1, 'lv': 8, 'k': sl['k'], 't': sl['t'], 'b': sl['b'],
             'dirk': f'Д{num} · {name}', 'note': sl.get('note', '') + f'  [дожим · блок {num}: {name}]'}
        if sl.get('disc'): s['disc'] = 1
        if 'cta-btn' in sl['b']: s['lv'] = 9
        new.append(s)
    S[pos + 1:pos + 1] = new
    added += len(new)
    print(f'✅ блок {num} «{name}» — {len(new)} слайдов после «{key}»')

