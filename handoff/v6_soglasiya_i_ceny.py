# -*- coding: utf-8 -*-
"""v6: согласия получены, цены сведены к каталогу, охотник — первым 20 на Silver и Gold.

Решения Влада 22.09:
  1. «$250–$1.200 это правильная цена» — цена AI-сайтов, каталог верен. В деке она уже стоит,
     расходилась только живая страница агента ($200–$800) — её правит не дека.
  2. «все кейсы называть можно» — согласия сняты как блокер. Аня возвращает суммы,
     предупреждения «⚠️ нужно согласие» уходят со слайдов учеников.
     Компании (ТІС, проекты «под ключ») это НЕ покрывает — там согласие даёт клиент, не Влад.
  3. «охотник бонусом только первым 20, первым голд и сильвер» — привязка выносится
     на экран, а не только в заметку суфлёра.

Плюс чиним конфликт, который вылез при сверке: у AI-таргета и AI-SEO в дожиме стояли
цены из старой версии ($300–$800 и $500), а в каталоге и на слайдах программы —
$600–$3.000 и $400–$1.800. В одном эфире две цены на одну услугу.

Запуск: python3 handoff/v6_soglasiya_i_ceny.py [--apply]
"""
import json, shutil, sys, datetime, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
F = os.path.join(ROOT, 'PREZA-EFIRA-v6.html')
APPLY = '--apply' in sys.argv

src = open(F, encoding='utf-8').read()
i = src.index('var S = [')
j = src.index('\n];', i)
S = json.loads(src[i + len('var S = '):j + 2])
log = []

def find(dirk, t=None):
    for n, s in enumerate(S):
        if s.get('dirk') == dirk and (t is None or s.get('t') == t):
            return n
    sys.exit(f'нет слайда {dirk} / {t}')

def swap(n, field, was, now, why):
    v = S[n].get(field) or ''
    if was not in v:
        log.append(f'  ⚠ #{n+1} не нашёл: {was[:70]}')
        return
    S[n][field] = v.replace(was, now)
    log.append(f'  ✓ #{n+1} [{S[n].get("dirk")}] {why}')

# ── 1. Аня: суммы возвращаются ────────────────────────────────────────────────
n = find('Б1 · Кейс Аня')
swap(n, 'b', '<div class="figure sm">3 месяца</div>', '<div class="figure sm">$2.000</div>',
     'Аня: вместо срока снова сумма')
swap(n, 'b', 'От переезда до своей фирмы. Было: релокация',
     'В месяц на AI-SEO — четыре клиента по $500. Было: релокация',
     'Аня: состав суммы в подписи')
S[n]['note'] = ('доказать, что система вытаскивает того, кто пришёл без направления. Аня пришла '
                'на стратсессию «в депрессионной Германии, непонятно что» — вышла с фирмой и '
                'налоговым номером. Из базы кейсов (видео 05): работала по 12 часов «и не сгорела», '
                'в 21:00 агент выкладывает четыре единицы контента, Threads-пост на 112 лайков, '
                '73 цитаты сайта в ответах нейросетей за 3,5 недели. Суммы называть можно — '
                'разрешение Влада 22.09.  [дожим · блок 1: Гарантия первого клиента]')
log.append(f'  ✓ #{n+1} Аня: суфлёр без запрета на суммы')

# ── 2. Стена кейсов: Аня снова с деньгами, заголовок про заработок ────────────
n = find('Б20 · Кейсы внедрения')
swap(n, 'b', 'Какую услугу оказали — и что с этого получили',
     'Какую услугу оказали — и сколько на ней заработали', 'стена: заголовок про деньги вернулся')
swap(n, 'b', 'Одна услуга — один ученик — его результат.', 'Одна услуга — один ученик — его деньги.',
     'стена: подпись про деньги вернулась')
swap(n, 'b',
     '<div class="usum"><b class="cnt" data-to="73" data-from="0" data-prefix="" '
     'data-suffix="" data-dot="1" data-dur="1300">73</b></div>'
     '<div class="usub">цитаты сайта в ответах нейросетей за 3,5 недели</div>',
     '<div class="usum"><b class="cnt" data-to="500" data-from="0" data-prefix="$" '
     'data-suffix="" data-dot="1" data-dur="1300">$500</b></div>'
     '<div class="usub">× 4 клиента в месяц · 73 цитаты в ответах нейросетей за 3,5 недели</div>',
     'Аня на стене: снова $500 × 4 клиента')
S[n]['st'] = ['new', 'кейсы можно называть по именам и суммам — разрешение Влада 22.09']
S[n]['note'] = S[n]['note'].replace(' По Ане суммы вслух не называть — согласия нет.', '')
log.append(f'  ✓ #{n+1} стена кейсов: флаг согласий снят')

# ── 3. Предупреждения «нужно согласие» со слайдов учеников ────────────────────
CLEAN = [
    ('Б3 · Кейс Юрий', None, ' ⚠️ Согласия на имя и суммы нет.'),
    ('Б8 · Дизайн и креативы', 'Светлана', ' ⚠️ Нужно письменное согласие Светланы на имя и цифру.'),
    ('Б10 · Продающие AI-видео', 'Женя', ' ⚠️ Нужно согласие Жени.'),
    ('Б16 · Контент и AI-аватар', 'Светлана · контент-завод', ' ⚠️ Нужно согласие.'),
]
for dirk, t, frag in CLEAN:
    n = find(dirk, t)
    if frag.strip() in (S[n].get('note') or ''):
        S[n]['note'] = S[n]['note'].replace(frag, '')
        log.append(f'  ✓ #{n+1} [{dirk}] снято предупреждение про согласие')
    else:
        log.append(f'  ⚠ #{n+1} [{dirk}] предупреждение не найдено')

n = find('Б9 · Саша и Антон')
S[n]['st'] = ['new', 'выдуманная «Наталья, 47» снята 21.09, правая колонка — Антон. Имена и суммы называть можно (22.09)']
log.append(f'  ✓ #{n+1} Саша и Антон: флаг обновлён')

# ── 4. Охотник: первым 20, только Silver и Gold — на экран ────────────────────
n = find('Б6 · CTA 3')
swap(n, 'b', 'Первым 20 броням этого эфира', 'Первым 20 броням · наборы Silver и Gold',
     'бонус: привязка к наборам вынесена на экран')
swap(n, 'b', 'бесплатно первым 20', 'бесплатно первым 20 на Silver и Gold',
     'бейдж бонуса: наборы названы')
S[n]['note'] = S[n]['note'].replace(
    'Привязку к Silver и Gold проговариваем на звонке: в момент брони набор ещё не выбран '
    '(это прямо сказано на «после брони» и «не набор, а решение»).',
    'Правило Влада 22.09: охотник — только первым двадцати и только на Silver и Gold. '
    'Теперь это написано на экране, проговорить дословно. Тем, кто в двадцатке с Bronze, '
    'на звонке объясняем: бонус открывается при переходе на Silver.')
log.append(f'  ✓ #{n+1} CTA 3: условие бонуса на экране')

n = find('Б12 · Агенты блока 4')
swap(n, 'b', 'готовый — в подарок первым 20 на Silver и Gold',
     'готовый — в подарок первым 20 на Silver и Gold', 'плитка охотника уже верна')

# ── 5. Цены услуг по каталогу ─────────────────────────────────────────────────
swap(n, 'b', '<em class="pr">$300–$800 · в месяц</em>', '<em class="pr">$600–$3.000 · в месяц</em>',
     'AI-таргет: цена сведена к каталогу')
swap(n, 'b', '<em class="pr">$500 · в месяц</em>', '<em class="pr">$400–$1.800 · в месяц</em>',
     'AI-SEO: цена сведена к каталогу')
S[n]['note'] = (S[n].get('note') or '') + (' Цены на плитках приведены к каталогу услуг: '
                'таргет $600–$3.000, SEO $400–$1.800 — те же, что на слайдах программы.')

print('\n'.join(log))
out = src[:i + len('var S = ')] + json.dumps(S, ensure_ascii=False, indent=1) + src[j + 2:]

if APPLY:
    stamp = datetime.datetime.now().strftime('%d%m-%H%M')
    shutil.copy(F, os.path.join(ROOT, f'PREZA-EFIRA-v6.pered-soglasiyami-{stamp}.html'))
    tmp = F + '.tmp'
    open(tmp, 'w', encoding='utf-8').write(out)
    os.replace(tmp, F)
    print('записано')
else:
    print('предпросмотр. записать: --apply')
