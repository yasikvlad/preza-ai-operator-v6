# -*- coding: utf-8 -*-
"""v6: пересчёт после выхода агента-охотника из программы.

Охотник уходит бонусом, значит его четыре задачи и его модуль больше не входят в блок 4:
  задачи блока 4: 12 → 8
  задачи программы: 46 → 42   (16 + 17 + 8 + 1; Bronze 16 и Silver 33 не меняются)
  модули Gold:     13 → 12    (M0–M12 без M10; Bronze 5 и Silver 8 не меняются)
Ценность $4.800 за набор задач НЕ трогаем: она зашита в накопитель элементов и в итоги
$6.060 / $12.390 / $21.350, которые стоят на восьми слайдах и в скрине банка.

Правится и мастер деки, и handoff/nabory_data.py — иначе следующая пересборка наборов
вернёт 13 и 46 обратно.

Запуск: python3 handoff/v6_chisla_42.py [--apply]
"""
import json, re, shutil, sys, datetime, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
F = os.path.join(ROOT, 'PREZA-EFIRA-v6.html')
ND = os.path.join(ROOT, 'handoff', 'nabory_data.py')
APPLY = '--apply' in sys.argv

src = open(F, encoding='utf-8').read()
i = src.index('var S = [')
j = src.index('\n];', i)
S = json.loads(src[i + len('var S = '):j + 2])

log = []

def fix(n, field, was, now, why):
    """Точечная замена в одном поле одного слайда, с проверкой что было."""
    s = S[n - 1]
    v = s.get(field) or ''
    if was not in v:
        log.append(f'  ⚠ #{n} [{s.get("dirk")}] не нашёл: {was[:60]}')
        return
    s[field] = v.replace(was, now)
    log.append(f'  ✓ #{n} [{s.get("dirk")}] {why}')

def find(dirk):
    for n, s in enumerate(S, 1):
        if s.get('dirk') == dirk:
            return n
    sys.exit(f'нет слайда {dirk}')

# ── 46 → 42 задачи ─────────────────────────────────────────────────────────────
ZAD_WAS = '46 готовых задач под ваши услуги'
ZAD_NOW = '42 готовые задачи под ваши услуги'

for dirk, field in [('Айсберг', 'b'), ('Элемент 3', 'b'), ('Набор Gold', 'b'), ('Стек целиком', 'b')]:
    fix(find(dirk), field, ZAD_WAS, ZAD_NOW, '46 → 42 задачи')

n = find('Элемент 3')
fix(n, 'note', 'Число: 46 готовых задач', 'Число: 42 готовые задачи', 'суфлёр: 46 → 42')

n = find('Б13 · Сравнить наборы')
fix(n, 'b', '<td>Готовых задач под ваши услуги</td><td>16</td><td>33</td><td>46</td>',
    '<td>Готовых задач под ваши услуги</td><td>16</td><td>33</td><td>42</td>', 'таблица: 16 / 33 / 42')

n = find('Б11 · Половина результата')
fix(n, 'b', 'Забудьте про 46 задач', 'Забудьте про 42 задачи', '46 → 42 в тексте')

# ── 13 → 12 модулей ────────────────────────────────────────────────────────────
for dirk, was, now in [
    ('Элемент 1', 'Полная система: 13 модулей · 10 недель', 'Полная система: 12 модулей · 10 недель'),
    ('Набор Gold', 'Полная система: 13 модулей', 'Полная система: 12 модулей'),
    ('Набор Gold', '7 агентов · 13 модулей', '7 агентов · 12 модулей'),
    ('Стек целиком', 'Полная система: 13 модулей · 5 блоков', 'Полная система: 12 модулей · 5 блоков'),
    ('Реальная цена', 'семь агентов · 13 модулей', 'семь агентов · 12 модулей'),
    ('Витрина цен', 'страт-сессии со мной · 13 модулей', 'страт-сессии со мной · 12 модулей'),
    ('Три набора', '<span>модулей</span><b>13</b>', '<span>модулей</span><b>12</b>'),
    ('Б13 · Сравнить наборы', '<td>Модулей программы</td><td>5</td><td>8</td><td>13</td>',
                              '<td>Модулей программы</td><td>5</td><td>8</td><td>12</td>'),
]:
    fix(find(dirk), 'b', was, now, '13 → 12 модулей')

# ── блок 4 в дожиме: счётчик и место охотника ──────────────────────────────────
n = find('Б12 · Агенты блока 4')
fix(n, 'b', '12 задач внутри · набор Gold',
    '8 задач внутри · охотник сверху, бонусом · набор Gold', 'счётчик 12 → 8, охотник назван бонусом')
fix(n, 'note', 'после блока 4 — два агента с чеком и охотник с функционалом',
    'после блока 4 — два агента с чеком; охотник идёт бонусом, а не третьим агентом блока',
    'суфлёр: охотник вне блока')

# ── обложка программы: охотник помечен бонусом ─────────────────────────────────
n = find('AI-Оператор')
fix(n, 'b', "<b>AI-Охотник</b><em>ищет клиентов</em>", "<b>AI-Охотник</b><em>ищет клиентов · бонус</em>",
    'на рабочем столе охотник помечен бонусом')

# ── блок 2: суфлёр про сумму ───────────────────────────────────────────────────
n = find('Блок 2 · сайты 9')
if '46 по всем блокам' in (S[n - 1].get('note') or ''):
    fix(n, 'note', '46 по всем блокам', '42 по всем блокам', 'суфлёр блока 2')

print('\n'.join(log))

# ── источник правды по наборам ─────────────────────────────────────────────────
nd_changed = False
if os.path.exists(ND):
    nd = open(ND, encoding='utf-8').read()
    nd2 = nd.replace('46 готовых задач под ваши услуги', '42 готовые задачи под ваши услуги') \
             .replace('Полная система: 13 модулей', 'Полная система: 12 модулей') \
             .replace("mod='13'", "mod='12'").replace("'mod': '13'", "'mod': '12'") \
             .replace("tasks='46'", "tasks='42'").replace("'tasks': '46'", "'tasks': '42'")
    nd_changed = nd2 != nd
    print('nabory_data.py:', 'правки есть' if nd_changed else 'нечего менять')

out = src[:i + len('var S = ')] + json.dumps(S, ensure_ascii=False, indent=1) + src[j + 2:]

if APPLY:
    stamp = datetime.datetime.now().strftime('%d%m-%H%M')
    shutil.copy(F, os.path.join(ROOT, f'PREZA-EFIRA-v6.pered-chislami-{stamp}.html'))
    tmp = F + '.tmp'
    open(tmp, 'w', encoding='utf-8').write(out)
    os.replace(tmp, F)
    if nd_changed:
        shutil.copy(ND, ND + f'.pered-42-{stamp}')
        open(ND, 'w', encoding='utf-8').write(nd2)
    print('записано')
else:
    print('предпросмотр. записать: --apply')
