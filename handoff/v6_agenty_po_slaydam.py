def route(items):
    """Нумерованный список задач — тот же компонент, что на слайдах блока 2."""
    return "<div class='route'>" + ''.join(
        f"<div class='rt'><i>{i:02d}</i><b>{b}</b><span>{s}</span></div>"
        for i, (b, s) in enumerate(items, 1)) + "</div>"

def tools(chips):
    """Нейронки, которыми работает агент. chips: [(подпись, файл логотипа или '')]"""
    out = []
    for name, logo in chips:
        img = f"<img src='assets/logo/{logo}' alt=''>" if logo else ''
        out.append(f"<span class='agtool'>{img}{name}</span>")
    return "<div class='agrow'>" + ''.join(out) + "</div>"

def bar(price=None, za=None, links=()):
    """Подвал слайда: цена услуги и ссылки на разбор работы агента."""
    if not price and not links:
        return ''
    p = f"<span class='agprice'>услуга <b>{price}</b> {za}</span>" if price else ''
    ls = ''.join(f"<a class='aglink' href='{u}' target='_blank' rel='noopener'>{t}</a>" for t, u in links)
    return f"<div class='agbar'>{p}{ls}</div>"

def out(text):
    return f"<div class='agout'><span>Результат блока</span><b>{text}</b></div>"

